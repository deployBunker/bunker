//go:build ignore

// gen_newercli_map.go regenerates newercli_releases_gen.go (DF-BUNKER-69).
//
// Run from the repository root (or anywhere in the tree):
//
//	go run cmd/bunker/gen_newercli_map.go
//
// Output path: cmd/bunker/newercli_releases_gen.go, beside main.go.
//
// For every subcommand registered on the real root command it derives — from
// git history, never from a hand-typed table — the release that first shipped
// it: the earliest commit that added its `cli.New<XxxCommand>()` registration
// to cmd/bunker/main.go, then the earliest tag containing that commit.
// Commands in no published release get an explicit "newer than <newest tag>"
// clause instead of an invented version number.
package main

import (
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"sort"
	"strings"
)

func main() {
	toplevel := firstLine(out("git", "rev-parse", "--show-toplevel"))
	newestTag := firstLine(out("git", "-C", toplevel, "tag", "--list", "--sort=-v:refname"))
	if newestTag == "" {
		fatal("no tags in this checkout; cannot anchor the untagged clause")
	}

	ctorByUse := ctorNamePairs(toplevel)
	names := make([]string, 0, len(ctorByUse))
	for name := range ctorByUse {
		names = append(names, name)
	}
	sort.Strings(names)
	if len(names) == 0 {
		fatal("no root.AddCommand(cli.New*Command()) calls found in cmd/bunker/main.go")
	}

	var b strings.Builder
	b.WriteString(`// Code generated by cmd/bunker/gen_newercli_map.go; DO NOT EDIT.
// Regenerate after adding or removing a root subcommand in newRootCommand:
//
//	go run cmd/bunker/gen_newercli_map.go
//
// DF-BUNKER-69: maps every root subcommand name to a clause naming the
// release that first shipped it ("release vX.Y.Z"), or, for commands that
// are in no published release yet, an explicit "newer than <newest release>"
// clause — never an invented version number.

package main

// newerCLISubcommandReleases is consumed by newerCLIArgs (args.go): when a
// client is asked for a name in this table that its own build does not
// register, the error names this release requirement instead of cobra's bare
// ` + "`unknown command`" + ` verdict. The registered-command check in newerCLIArgs
// means a stale entry can never shadow a command this build actually has.
var newerCLISubcommandReleases = map[string]string{
`)
	for _, name := range names {
		ctor, ok := ctorByUse[name]
		if !ok {
			fatal(fmt.Sprintf("constructor for subcommand %q not found in cmd/bunker/main.go root.AddCommand calls", name))
		}
		fmt.Fprintf(&b, "	%q: %q,\n", name, releaseClause(toplevel, name, ctor, newestTag))
	}
	b.WriteString("}\n")

	// Resolve the output path relative to the invocation directory: running
	// `go run cmd/bunker/gen_newercli_map.go` from the repository root (the
	// documented invocation) must land the file beside main.go.
	outPath := "newercli_releases_gen.go"
	if _, err := os.Stat("cmd/bunker/main.go"); err == nil {
		outPath = "cmd/bunker/newercli_releases_gen.go"
	}

	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		fatal(err.Error())
	}
	// Keep the generated file gofmt-stable (map-value alignment drifts
	// otherwise); a missing gofmt binary is a warning, not a failure — the
	// file is still correct Go.
	if c := exec.Command("gofmt", "-w", outPath); c.Run() != nil {
		fmt.Println("warning: gofmt not available; run `gofmt -w " + outPath + "` manually")
	}
	fmt.Printf("wrote %s: %d subcommands, newest tag %s\n", outPath, len(names), newestTag)
}

// releaseClause returns the "first available in ..." clause body for name:
// "release vX.Y.Z" for a tagged introduction, or an explicit newer-than
// clause when no published release contains the introducing commit. The
// ctor↔Use mapping comes from ctorNamePairs — read from the AddCommand calls
// and each constructor's Use: declaration, never name-guessed.
func releaseClause(toplevel, name, ctor, newestTag string) string {
	first := firstLine(out("git", "-C", toplevel, "log", "-S"+ctor, "--format=%H", "--", "cmd/bunker/main.go"))
	if first == "" {
		fatal(fmt.Sprintf("no commit found introducing %q to cmd/bunker/main.go; the AddCommand convention broke for %q", ctor, name))
	}
	earliest := firstLine(out("git", "-C", toplevel, "tag", "--contains", first, "--sort=v:refname"))
	if earliest == "" {
		return fmt.Sprintf("a release newer than %s, the newest published release", newestTag)
	}
	return "release " + earliest
}

// ctorNamePairs parses the CURRENT cmd/bunker/main.go root.AddCommand calls
// and returns cobra-name → constructor-call pairs by reading each constructor
// function's definition site for its Use: string. Name changes and word
// additions both regenerate correctly.
func ctorNamePairs(toplevel string) map[string]string {
	mainGo := out("cat", toplevel+"/cmd/bunker/main.go")
	pairs := map[string]string{}
	for _, m := range regexp.MustCompile(`root\.AddCommand\((cli\.\w+)`).FindAllStringSubmatch(mainGo, -1) {
		call := m[1]
		// Definition sites declare `func NewXxxCommand(...)` — the cli.
		// qualifier exists only at the call site.
		defName := strings.TrimPrefix(call, "cli.")
		// Find the constructor's definition site: cmd/bunker first, then
		// internal/cli (definition files are small enough to grep + read).
		var file string
		for _, dir := range []string{toplevel + "/cmd/bunker", toplevel + "/internal/cli"} {
			c := exec.Command("grep", "-rl", "--", "func "+defName, dir)
			c.Stderr = nil
			b, err := c.Output()
			if err != nil {
				continue
			}
			file = firstLine(string(b))
			if file != "" {
				break
			}
		}
		if file == "" {
			fatal("definition site not found for " + call)
		}
		src := out("cat", file)
		m := regexp.MustCompile(`Use:\s*"([^"]+)"`).FindStringSubmatch(src)
		if m == nil {
			fatal("no Use: string found in " + file + " for " + call)
		}
		name := strings.Fields(m[1])[0]
		pairs[name] = call
	}
	return pairs
}

func out(argv ...string) string {
	c := exec.Command(argv[0], argv[1:]...)
	c.Stderr = os.Stderr
	b, err := c.Output()
	if err != nil {
		fatal(fmt.Sprintf("%v: %v", argv, err))
	}
	return string(b)
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	return strings.TrimSpace(s)
}

func fatal(msg string) {
	fmt.Fprintln(os.Stderr, "gen_newercli_map: "+msg)
	os.Exit(1)
}
